function getIsoAlpha2(): readonly string[] {
  return ISO_ALPHA_2;
}

const optionsCache = new Map<string, CountryOption[]>();

export function getCountryOptions(locale: string): CountryOption[] {
  const cached = optionsCache.get(locale);
  if (cached) return cached;
  const dn = new Intl.DisplayNames([locale], { type: 'region' });
  const codes = getIsoAlpha2();
  const sorted = codes
    .filter((code) => !PINNED_COUNTRIES.includes(code))
    .map((code) => ({ code, name: dn.of(code) ?? code, pinned: false }))
    .sort((a, b) => a.name.localeCompare(b.name, locale));
  const pinned = PINNED_COUNTRIES.map((code) => ({
    code,
    name: dn.of(code) ?? code,
    pinned: true,
  }));
  const result = [...pinned, ...sorted];
  optionsCache.set(locale, result);
  return result;
}

export function formatCountryName(code: string | null | undefined, locale: string): string | null {
  if (!code) return null;
  return new Intl.DisplayNames([locale], { type: 'region' }).of(code) ?? code;
}
