/**
 * Country list + helpers for the event-creation wizard.
 *
 * The wizard stores ISO 3166-1 alpha-2 codes (FR, DE, US, …) in
 * `events.country`. We render localised country names via
 * `Intl.DisplayNames` so the i18n table stays empty — EN sees
 * "Germany", FR sees "Allemagne", both for the same DB value DE.
 *
 * The alpha-2 code list is hardcoded because Intl.supportedValuesOf
 * doesn't enumerate regions (only calendar/collation/currency/…).
 * It's a stable ISO list — additions are rare and trivial to apply.
 */

