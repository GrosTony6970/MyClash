#!/usr/bin/env node
/**
 * Generates packages/ui/src/components/nav-icon-glyphs.ts — the vendored path
 * data for the 51 glyphs the sidebars use.
 *
 * ── Why vendor at all ───────────────────────────────────────────────────────
 * `packages/ui` compiles to CommonJS, so a `require('lucide-react')` is opaque
 * to the bundler and the whole 2,011-icon barrel ships: 188 KB gzip, in a chunk
 * every app's root layout names in `entryJSFiles`, i.e. on every page load of
 * all three apps. The 51 nodes below are 4 KB gzip.
 *
 * ── Why a generator rather than a hand-written file ─────────────────────────
 * Vendored artwork rots silently: lucide redraws icons between minor versions
 * and nothing here would notice. `nav-icon-glyphs.test.ts` calls
 * `renderGlyphModule()` on every test run and asserts the committed file is
 * byte-identical, so an upgrade that changes a path turns a suite red and the
 * fix is re-running this script.
 *
 * The glyph LIST is not stored here — it is read out of `NAV_ICON_GLYPHS` in
 * NavIcon.tsx, which is the one place that decides which artwork the product
 * needs. The regex below is a convenience, not the guarantee: the test asserts
 * set-equality between the map's values and this module's keys at runtime, so a
 * misread shows up as a failure rather than a missing icon.
 *
 * Deep-importing `lucide-react/dist/esm/icons/<name>.mjs` at runtime instead is
 * not an option: tsc would emit `require()` of an `.mjs`, which Turbopack
 * tolerates and node does not — and the render test runs under node.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const require = createRequire(import.meta.url);

const PACKAGE_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const NAV_ICON_SOURCE = join(PACKAGE_ROOT, 'src', 'components', 'NavIcon.tsx');
export const GLYPH_MODULE_PATH = join(PACKAGE_ROOT, 'src', 'components', 'nav-icon-glyphs.ts');

/** Every glyph name `NAV_ICON_GLYPHS` points at, de-duplicated and sorted. */
export function glyphNamesInUse(source = readFileSync(NAV_ICON_SOURCE, 'utf8')) {
  const start = source.indexOf('export const NAV_ICON_GLYPHS');
  if (start === -1) throw new Error('NAV_ICON_GLYPHS not found in NavIcon.tsx');
  const end = source.indexOf('\n};', start);
  if (end === -1) throw new Error('NAV_ICON_GLYPHS is not closed');
  const body = source.slice(start, end);

  const names = [...body.matchAll(/^\s*[\w]+: '([a-z0-9-]+)',$/gm)].map((match) => match[1]);
  if (names.length === 0)
    throw new Error('NAV_ICON_GLYPHS matched no entries — has its shape changed?');
  return [...new Set(names)].sort();
}

/** The `__iconNode` array lucide ships for one glyph. */
async function readIconNode(name) {
  const lucideRoot = dirname(require.resolve('lucide-react/package.json'));
  const iconFile = join(lucideRoot, 'dist', 'esm', 'icons', `${name}.mjs`);
  let module;
  try {
    module = await import(pathToFileURL(iconFile).href);
  } catch (cause) {
    throw new Error(
      `lucide-react ships no glyph called '${name}' (looked in dist/esm/icons/${name}.mjs). ` +
        'Check the name in NAV_ICON_GLYPHS against https://lucide.dev/icons.',
      { cause },
    );
  }
  if (!Array.isArray(module.__iconNode)) {
    throw new Error(`lucide's ${name}.mjs no longer exports an __iconNode array.`);
  }
  return module.__iconNode;
}

/** The full text of nav-icon-glyphs.ts, prettier-formatted. */
export async function renderGlyphModule(names = glyphNamesInUse()) {
  const entries = [];
  for (const name of names) {
    entries.push(`  '${name}': ${JSON.stringify(await readIconNode(name))},`);
  }

  const { version } = require('lucide-react/package.json');
  const source = `// GENERATED by packages/ui/scripts/generate-nav-icons.mjs — do not edit by hand.
// Path data vendored from lucide-react ${version} (ISC). Re-run the generator
// after changing NAV_ICON_GLYPHS in NavIcon.tsx; nav-icon-glyphs.test.ts fails
// until you do.

/** One SVG child of a glyph: a tag plus its attributes, React-prop-cased. */
export type IconNode = readonly (readonly [string, Readonly<Record<string, string>>])[];

export const LUCIDE_GLYPHS = {
${entries.join('\n')}
} as const satisfies Readonly<Record<string, IconNode>>;

export type GlyphName = keyof typeof LUCIDE_GLYPHS;
`;

  const prettier = await import('prettier');
  const config = (await prettier.resolveConfig(GLYPH_MODULE_PATH)) ?? {};
  return prettier.format(source, { ...config, filepath: GLYPH_MODULE_PATH });
}

// ── CLI ──────────────────────────────────────────────────────────────────────
// `--check` regenerates and compares instead of writing; nav-icon-glyphs.test.ts
// runs it that way, so the drift assertion and the fix are the same code path.
// Guarded so importing this module never touches disk.
if (process.argv[1] && process.argv[1].endsWith('generate-nav-icons.mjs')) {
  const names = glyphNamesInUse();
  const text = await renderGlyphModule(names);

  if (process.argv.includes('--check')) {
    const committed = readFileSync(GLYPH_MODULE_PATH, 'utf8');
    if (committed !== text) {
      console.error(
        'packages/ui/src/components/nav-icon-glyphs.ts is out of date with lucide-react.\n' +
          'Either NAV_ICON_GLYPHS changed, or a lucide upgrade redrew a glyph.\n' +
          'Fix: node packages/ui/scripts/generate-nav-icons.mjs',
      );
      process.exitCode = 1;
    } else {
      console.log(`nav-icon-glyphs.ts matches lucide-react for all ${names.length} glyphs.`);
    }
  } else {
    writeFileSync(GLYPH_MODULE_PATH, text);
    console.log(`Wrote ${names.length} glyphs to ${GLYPH_MODULE_PATH}`);
  }
}
